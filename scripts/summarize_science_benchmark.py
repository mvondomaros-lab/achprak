        "Loose and tight mean force thresholds of 0.01 and 0.002 eV/Å, respectively. Energy change is E(loose) − E(tight); spectral peak change has the same subtraction order. Steps and extra time describe continuation of the same optimization. True means the numerical stopping criterion was met. All rows retain the same composition and method.",
