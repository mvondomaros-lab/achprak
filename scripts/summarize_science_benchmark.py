        "This comparison alone cannot identify the more accurate method.",
        "",
        "## Reading the tables",
        "",
        "Energies use electronvolts (eV) per molecule or kilojoules per mole (kJ mol⁻¹). "
        "Lengths use ångströms (Å). A force threshold in eV/Å controls when structure optimization stops. "
        "A seed fixes the random numbers used to generate a reproducible starting structure. "
        "H denotes the unsubstituted parent; Me, OMe and NMe2 denote methyl, methoxy and dimethylamino groups.",
        "",
        "## Scope",
        "",
        "Recorded sensitivity study using the Pixi development environment listed below, one numerical-library compute thread, "
        "ALPB ethanol structures, xTB accuracy 0.1, and INDO/S–CIS with COSMO EPS=24.3. "
        "The initial three-dimensional structure is generated by RDKit's ETKDGv3 method with seed 42 unless stated.",
